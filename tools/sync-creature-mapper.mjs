import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { MAPPER_FILES, mapperSnapshot, normalize, verifyMapperSnapshot } from "./mapper-snapshot.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const destination = join(root, "scripts/creatures/generated/dnd-foundry");
const snapshotPath = join(root, "tools/creature-mapper.lock.json");
const files = ["export.mjs", "schema.mjs", "defenses.mjs", "items.mjs", "spells.mjs"];
let check = false;
let source;
const args = process.argv.slice(2);
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--check" && !check) check = true;
  else if (args[i] === "--source" && !source && args[i + 1] && !args[i + 1].startsWith("--")) source = resolve(args[++i]);
  else throw new Error("Usage: npm run creatures:sync -- --source <website-mapper-directory> [--check]");
}
if (!check && !source) throw new Error("Mapper synchronization requires an explicit --source directory.");

if (source) {
  const digest = createHash("sha256");
  const outputs = new Map();
  for (const file of [...files, "read-result.mjs"]) {
    // Working-copy CRLF does not change the canonical source hash.
    const content = normalize(await readFile(join(source, file), "utf8"));
    digest.update(file + "\n" + content);
    if (files.includes(file)) outputs.set(file, content);
    else {
      const fields = content.match(/const FIELDS = Object\.freeze\((\{[\s\S]*?\})\);/);
      if (!fields) throw new Error("Cannot locate canonical record fields");
      outputs.set("record-fields.mjs", `// Generated from the website selected-source reader; do not edit.\nexport const FIELDS = Object.freeze(${fields[1]});\n`);
    }
  }
  outputs.set("version.mjs", `// Generated by tools/sync-creature-mapper.mjs; do not edit.\nexport const MAPPER_VERSION = "${digest.digest("hex")}";\n`);
  if (!check) await mkdir(destination, { recursive: true });
  for (const [file, expected] of outputs) {
    if (check) {
      const actual = normalize(await readFile(join(destination, file), "utf8"));
      if (actual !== expected) throw new Error(`Stale creature mapper: ${file}. Run npm run creatures:sync -- --source <website-mapper-directory>.`);
    } else await writeFile(join(destination, file), expected);
  }
  if (!check) await writeFile(snapshotPath, `${JSON.stringify(mapperSnapshot(outputs), null, 2)}\n`);
  console.log(check ? "Creature mapper matches the supplied canonical website source." : "Synchronized creature mapper and snapshot.");
}
const installed = new Map(await Promise.all(MAPPER_FILES.map(async file =>
  [file, await readFile(join(destination, file), "utf8")])));
verifyMapperSnapshot(installed, JSON.parse(await readFile(snapshotPath, "utf8")));
console.log("Creature mapper matches the standalone repository snapshot.");
